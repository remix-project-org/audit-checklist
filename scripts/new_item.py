#!/usr/bin/env python3
"""Emit a new checklist item in the tagged schema from an official source plus drafted text.

The question/description/remediation come from a draft JSON file (written by a person
or generated by a model). Everything that can be derived deterministically comes
from the official source, never from the draft:

  solidity-bug  applicability.solc / compiler_settings, severity_prior and provenance
                from ethereum/solidity docs/bugs.json (cross-checked against
                bugs_by_version.json when given)
  ghsa          applicability.dependencies, severity_prior and provenance from OSV.dev
                data for @openzeppelin/contracts[-upgradeable]

New items are always `review_status: needs_review`.

Draft file: {"question": "...", "description": "...", "remediation": "...",
             "features": ["inherits:Foo"]  (optional, applicability.any_of for ghsa / all_of for solidity-bug),
             "ast_pattern": "..."          (optional)}

Usage:
  python scripts/new_item.py solidity-bug SOL-2026-7 --draft draft.json --solidity-bugs bugs.json [--bugs-by-version bugs_by_version.json] [--insert]
  python scripts/new_item.py ghsa GHSA-9rcw-c2f9-2j55 --draft draft.json --osv-dir osv [--insert]

Without --insert the item is printed to stdout. With --insert it is appended to the
Solidity or OpenZeppelin Version Issues category with the next free ID, and the
checklist is validated.
"""

from __future__ import annotations

import argparse
import datetime
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import backfill_tags as bt  # noqa: E402
import checklist_lib as lib  # noqa: E402

TARGETS = {
    "solidity-bug": (("Basics", "Version Issues", "Solidity Version Issues"), "SOL-Basics-VI-SVI-", "compiler-bug"),
    "ghsa": (("Basics", "Version Issues", "OpenZeppelin Version Issues"), "SOL-Basics-VI-OVI-", "dependency-vulnerability"),
}


def next_id(data, prefix: str) -> str:
    nums = [int(m.group(1)) for _, i in lib.iter_items(data) if (m := re.match(re.escape(prefix) + r"(\d+)$", i["id"]))]
    return f"{prefix}{max(nums, default=0) + 1}"


def build(kind: str, source_id: str, draft: dict, args, item_id: str) -> dict:
    for field in ("question", "description", "remediation"):
        if not isinstance(draft.get(field), str) or not draft[field].strip():
            raise SystemExit(f"draft is missing {field!r}")
    features = draft.get("features") or []
    date = datetime.date.today().isoformat()

    if kind == "solidity-bug":
        bugs = lib.load_json(args.solidity_bugs)
        bug = next((b for b in bugs if source_id in (b.get("uid"), b["name"])), None)
        if bug is None:
            raise SystemExit(f"{source_id} not found in {args.solidity_bugs}")
        applicability = bt.bug_applicability(bug)
        if features:
            applicability["all_of"] = features
        notes = ["Generated item; question and description not reviewed."]
        if args.bugs_by_version:
            diff = bt.check_bug_against_versions(bug, applicability, lib.load_json(args.bugs_by_version))
            if diff:
                notes.append(f"solc range disagrees with bugs_by_version.json on {', '.join(diff)}.")
        severity = bt.BUG_SEVERITY[bug["severity"]]
        sources = [{"type": "solidity_bugs_json", "ref": bug.get("uid", bug["name"]), "url": bt.BUGS_JSON_URL}]
        references = []
        if bug.get("link"):
            sources.append({"type": "solidity_blog", "url": bug["link"]})
            references.append(bug["link"])
        prop = "Deterministic: compiler version and settings match the range; then confirm the triggering construct is present."
    else:
        adv = bt.osv_index(Path(args.osv_dir)).get(source_id)
        if adv is None or not adv["ranges"]:
            raise SystemExit(f"{source_id} not found in OSV data under {args.osv_dir}; do not guess advisory data")
        applicability = {
            **({"any_of": bt.upgradeable_variants(features)} if features else {}),
            "dependencies": [{"package": p, "range": r} for p, r in sorted(adv["ranges"].items())],
        }
        notes = ["Generated item; question and description not reviewed."]
        if not features:
            notes.append("No affected contract/library feature given; applicability matches on version only.")
        severity = bt.GHSA_SEVERITY.get(adv["severity"] or "", "medium")
        url = bt.GHSA_URL.format(source_id)
        sources = [{"type": "ghsa", "ref": source_id, "url": url}]
        references = [url]
        prop = "Deterministic: installed OpenZeppelin version is in range; then confirm the affected contract or function is used."

    item = {
        "id": item_id,
        "question": draft["question"].strip(),
        "description": draft["description"].strip(),
        "remediation": draft["remediation"].strip(),
        "references": references,
        "tags": [],
        "vuln_category": TARGETS[kind][2],
        "severity_prior": severity,
        "applicability": applicability,
        "verification": {"method": "manual_only", "property": prop},
        "provenance": {"sources": sources, "last_reviewed": date},
        "review_status": "needs_review",
        "review_notes": " ".join(notes),
    }
    if draft.get("ast_pattern"):
        item["detection_hint"] = {"ast_pattern": draft["ast_pattern"]}
    return lib.order_item_fields(item)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("kind", choices=sorted(TARGETS))
    ap.add_argument("source_id", help="bugs.json uid or name, or a GHSA id")
    ap.add_argument("--draft", required=True)
    ap.add_argument("--solidity-bugs")
    ap.add_argument("--bugs-by-version")
    ap.add_argument("--osv-dir")
    ap.add_argument("--checklist", default=str(lib.CHECKLIST_PATH))
    ap.add_argument("--insert", action="store_true")
    args = ap.parse_args(argv)
    if args.kind == "solidity-bug" and not args.solidity_bugs:
        ap.error("solidity-bug needs --solidity-bugs")
    if args.kind == "ghsa" and not args.osv_dir:
        ap.error("ghsa needs --osv-dir")

    data = lib.load_json(args.checklist)
    path, prefix, _ = TARGETS[args.kind]
    item = build(args.kind, args.source_id, lib.load_json(args.draft), args, next_id(data, prefix))
    if not args.insert:
        print(json.dumps(item, indent=4))
        return 0

    import sync_upstream
    import validate
    sync_upstream.find_category(data, path)["data"].append(item)
    lib.dump_checklist(data, args.checklist)
    errors, _, _ = validate.validate(Path(args.checklist), lib.SCHEMA_PATH, lib.VOCABULARY_PATH)
    for e in errors:
        print(f"error: {e}")
    print(f"inserted {item['id']}" + (" (validation FAILED)" if errors else ""))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
